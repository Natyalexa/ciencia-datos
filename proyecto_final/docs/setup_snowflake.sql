-- Preparación de Snowflake para el PSet #2 (ejecutar una sola vez como ACCOUNTADMIN).
-- Antes: genera el par de llaves (ver README) y pega la llave PÚBLICA en RSA_PUBLIC_KEY,
-- sin las líneas BEGIN/END y sin saltos de línea.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS PSET2_ROLE;

CREATE WAREHOUSE IF NOT EXISTS PSET2_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS PSET2_DB;
CREATE SCHEMA IF NOT EXISTS PSET2_DB.RAW;
CREATE SCHEMA IF NOT EXISTS PSET2_DB.BRONZE;
CREATE SCHEMA IF NOT EXISTS PSET2_DB.SILVER;
CREATE SCHEMA IF NOT EXISTS PSET2_DB.GOLD;
CREATE SCHEMA IF NOT EXISTS PSET2_DB.OBT;

GRANT USAGE, OPERATE ON WAREHOUSE PSET2_WH TO ROLE PSET2_ROLE;
GRANT ALL PRIVILEGES ON DATABASE PSET2_DB TO ROLE PSET2_ROLE;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE PSET2_DB TO ROLE PSET2_ROLE;
GRANT ALL PRIVILEGES ON FUTURE SCHEMAS IN DATABASE PSET2_DB TO ROLE PSET2_ROLE;

-- Usuario de servicio (autenticación solo por llave; sin contraseña)
CREATE USER IF NOT EXISTS PSET2_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = PSET2_ROLE
  DEFAULT_WAREHOUSE = PSET2_WH
  RSA_PUBLIC_KEY = 'PEGA_AQUI_LA_LLAVE_PUBLICA';

GRANT ROLE PSET2_ROLE TO USER PSET2_SVC;

-- Opcional: para consultar las tablas del proyecto desde tu usuario administrador
GRANT ROLE PSET2_ROLE TO ROLE ACCOUNTADMIN;
